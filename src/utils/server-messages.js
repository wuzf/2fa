// Preserve the original three-column source catalog for tooling while exposing
// a locale-addressed registry to every renderer and diagnostic compiler.
const translatedRows = new WeakMap();
export function getServerTranslations(row) {
	if (!translatedRows.has(row)) {
		const [simplified, traditional, english] = row;
		translatedRows.set(
			row,
			Object.freeze(
				Object.fromEntries(
					SUPPORTED_LANGUAGES.map((language) => [
						language,
						language === 'zh-CN' ? simplified : language === 'zh-TW' ? traditional : translateEnglish(language, english),
					]),
				),
			),
		);
	}
	return translatedRows.get(row);
}
